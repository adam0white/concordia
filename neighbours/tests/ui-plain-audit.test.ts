import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { afterEach, expect, it, vi } from "vitest";
import PersonPanel from "../src/ui/PersonPanel";
import { needWords, trustWords } from "../src/ui/person-status";
import TownInspector from "../src/ui/TownInspector";
import type { useVisitorSession } from "../src/ui/useVisitorSession";
import { createRuntime } from "./historical-runtime";

afterEach(() => vi.unstubAllGlobals());

it("names one person in fallback impressions and trust without assuming gender", () => {
	expect(needWords({ food: 0.9 }, "Nora")).toBe("Nora looks very hungry.");
	expect(trustWords(0.5, "Nora")).toBe("Nora trusts this person");
});

it("keeps numeric decision records behind the exact lab flag", () => {
	const town = createRuntime(42, 8).view();
	const person = town.people[0];
	if (!person) throw new Error("Missing resident");
	person.decision = {
		chosen: "rest",
		label: "Rest",
		reason: "I need to rest.",
		source: "Exact HF source stamp",
		options: [{ id: "rest", label: "Rest", utility: 0.987 }],
	};
	const render = () =>
		renderToStaticMarkup(
			createElement(PersonPanel, {
				person,
				town,
				close: () => {},
				observed: undefined,
			}),
		);
	for (const search of ["", "?lab=true", "?lab=0"]) {
		vi.stubGlobal("location", { search });
		const html = render();
		expect(html).toContain("I need to rest.");
		expect(html).not.toContain("Controller · HF");
		expect(html).not.toContain("Exact HF source stamp");
		expect(html).not.toContain("0.987");
	}
	vi.stubGlobal("location", { search: "?lab=1" });
	const html = render();
	expect(html).toContain("Controller · HF");
	expect(html).toContain("Exact HF source stamp");
	expect(html).toContain("0.987");
});

it("does not mount recorded research reports outside lab mode", () => {
	vi.stubGlobal("location", { search: "" });
	const session = { town: createRuntime(42, 8).view() } as ReturnType<
		typeof useVisitorSession
	>;
	expect(
		renderToStaticMarkup(
			createElement(TownInspector, { session, section: "recorded" }),
		),
	).toBe("");
});

it("keeps AI and comparison policy distinctions visible outside lab mode", () => {
	vi.stubGlobal("location", { search: "" });
	const town = createRuntime(42, 8).view();
	const person = town.people[0];
	if (!person) throw new Error("Missing resident");
	for (const [policy, label] of [
		["llm", "Recorded choice generated by an AI model."],
		["table", "Choices follow a fixed set of rules."],
		["random", "Choices are picked at random."],
	] as const) {
		person.policy = policy;
		const html = renderToStaticMarkup(
			createElement(PersonPanel, {
				person,
				town,
				close: () => {},
				observed: undefined,
			}),
		);
		expect(html).toContain(label);
		expect(html).not.toContain("Controller ·");
	}
});
